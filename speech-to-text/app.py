
from fastapi import FastAPI, UploadFile, File
from fastapi.responses import FileResponse
from faster_whisper import WhisperModel
from pathlib import Path
from datetime import datetime, timezone
import json
import os
import uuid

app = FastAPI()

# ── Paths ──────────────────────────────────────────────────────
# The pipeline copies the generated video here before launch.
APP_DIR = Path(__file__).resolve().parent
VIDEO_PATH = APP_DIR / "avatar_question.mp4"

# Directory for saved recordings and transcripts.
DATA = Path(os.environ.get("RECORDINGS_DIR", APP_DIR / "recordings"))
DATA.mkdir(parents=True, exist_ok=True)

# ── Load Whisper model at startup ──────────────────────────────
model = WhisperModel(
    os.environ.get("WHISPER_MODEL", "base.en"),
    device=os.environ.get("WHISPER_DEVICE", "cpu"),
    compute_type=os.environ.get("WHISPER_COMPUTE_TYPE", "int8"),
)


# ── Routes ─────────────────────────────────────────────────────

@app.get("/")
def home():
    """Serve the main assessment page."""
    return FileResponse(APP_DIR / "index.html")


@app.get("/health")
def health():
    """Health check used by the service manager and reverse proxy."""
    return {"status": "ok"}


@app.get("/video")
def serve_video():
    """Serve the AI avatar question video generated by Wav2Lip."""
    if not VIDEO_PATH.is_file():
        return {"error": "Avatar video not found. Run the pipeline first."}
    return FileResponse(
        path=str(VIDEO_PATH),
        media_type="video/mp4",
        filename="avatar_question.mp4",
    )


@app.post("/transcribe")
async def transcribe(audio: UploadFile = File(...)):
    """Receive audio from the browser and transcribe it."""

    # Generate a descriptive, unique filename.
    exam_id = "exam_001"

    timestamp = datetime.now(timezone.utc).strftime(
        "%Y%m%d_%H%M%S"
    )

    recording_id = (
        f"{exam_id}_{timestamp}_{uuid.uuid4().hex[:8]}"
    )

    # Save the original audio recording.
    audio_path = DATA / f"{recording_id}.webm"

    audio_path.write_bytes(await audio.read())

    # Transcribe the recording locally.
    segments, info = model.transcribe(
        str(audio_path),
        language="en"
    )

    text = " ".join(
        segment.text.strip() for segment in segments
    ).strip()

    # Prepare the transcript entry.
    entry = {
        "exam_id": exam_id,
        "recording_id": recording_id,
        "speaker": "student",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "text": text
    }

    # Save the individual transcript as a text file.
    text_path = DATA / f"{recording_id}.txt"

    text_path.write_text(
        text,
        encoding="utf-8"
    )

    # Append the response to the cumulative transcript.
    with open(
        DATA / "transcript.jsonl",
        "a",
        encoding="utf-8"
    ) as file:
        file.write(json.dumps(entry) + "\n")

    # Return the transcript to the browser.
    return entry
